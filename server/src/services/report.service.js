import PDFDocument from 'pdfkit';

/**
 * Generate a PDF report from scan data
 * @param {object} reportData - The report data object
 * @returns {Promise<Buffer>} PDF buffer
 */
export const generatePDFReport = async (reportData) => {
  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({ size: 'A4', margin: 50 });
      const chunks = [];

      doc.on('data', (chunk) => chunks.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(chunks)));

      // Header
      doc.fontSize(24).fillColor('#059669').text('🌿 PlantSense AI', { align: 'center' });
      doc.moveDown(0.3);
      doc.fontSize(16).fillColor('#064e3b').text('Plant Health Report', { align: 'center' });
      doc.moveDown(0.3);
      doc.fontSize(10).fillColor('#6b7280').text(`Generated on ${new Date().toLocaleDateString('en-US', { dateStyle: 'long' })}`, { align: 'center' });
      doc.moveDown(1);

      // Divider
      doc.strokeColor('#d1fae5').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
      doc.moveDown(1);

      // Disease Info
      const disease = reportData.disease || {};
      doc.fontSize(14).fillColor('#064e3b').text('Disease Detection Results');
      doc.moveDown(0.5);
      doc.fontSize(11).fillColor('#374151');
      doc.text(`Disease: ${disease.name || 'N/A'}`);
      doc.text(`Confidence: ${disease.confidence || 0}%`);
      doc.text(`Severity: ${(disease.severity || 'N/A').toUpperCase()}`);
      doc.text(`Health Score: ${reportData.healthScore || 0}/100`);
      doc.moveDown(0.5);

      if (disease.description) {
        doc.text(`Description: ${disease.description}`, { width: 495 });
      }
      doc.moveDown(1);

      // Symptoms
      if (reportData.symptoms?.length) {
        doc.fontSize(14).fillColor('#064e3b').text('Symptoms');
        doc.moveDown(0.3);
        doc.fontSize(11).fillColor('#374151');
        reportData.symptoms.forEach((s) => doc.text(`  • ${s}`, { width: 495 }));
        doc.moveDown(0.8);
      }

      // Causes
      if (reportData.causes?.length) {
        doc.fontSize(14).fillColor('#064e3b').text('Causes');
        doc.moveDown(0.3);
        doc.fontSize(11).fillColor('#374151');
        reportData.causes.forEach((c) => doc.text(`  • ${c}`, { width: 495 }));
        doc.moveDown(0.8);
      }

      // Treatments
      const treatments = reportData.treatments || {};
      if (treatments.organic?.length || treatments.chemical?.length || treatments.homeRemedies?.length) {
        doc.fontSize(14).fillColor('#064e3b').text('Treatment Recommendations');
        doc.moveDown(0.3);
        doc.fontSize(11).fillColor('#374151');

        if (treatments.organic?.length) {
          doc.fontSize(12).fillColor('#059669').text('Organic:');
          treatments.organic.forEach((t) => doc.fontSize(11).fillColor('#374151').text(`  • ${t}`, { width: 495 }));
          doc.moveDown(0.3);
        }
        if (treatments.chemical?.length) {
          doc.fontSize(12).fillColor('#d97706').text('Chemical:');
          treatments.chemical.forEach((t) => doc.fontSize(11).fillColor('#374151').text(`  • ${t}`, { width: 495 }));
          doc.moveDown(0.3);
        }
        if (treatments.homeRemedies?.length) {
          doc.fontSize(12).fillColor('#7c3aed').text('Home Remedies:');
          treatments.homeRemedies.forEach((t) => doc.fontSize(11).fillColor('#374151').text(`  • ${t}`, { width: 495 }));
        }
        doc.moveDown(0.8);
      }

      // Prevention
      if (reportData.prevention?.length) {
        doc.fontSize(14).fillColor('#064e3b').text('Prevention Tips');
        doc.moveDown(0.3);
        doc.fontSize(11).fillColor('#374151');
        reportData.prevention.forEach((p) => doc.text(`  • ${p}`, { width: 495 }));
        doc.moveDown(0.8);
      }

      // Recovery time
      if (reportData.recoveryTime) {
        doc.fontSize(14).fillColor('#064e3b').text('Recovery Time');
        doc.moveDown(0.3);
        doc.fontSize(11).fillColor('#374151').text(reportData.recoveryTime);
        doc.moveDown(0.8);
      }

      // Footer
      doc.moveDown(2);
      doc.strokeColor('#d1fae5').lineWidth(1).moveTo(50, doc.y).lineTo(545, doc.y).stroke();
      doc.moveDown(0.5);
      doc.fontSize(9).fillColor('#9ca3af').text('This report was generated by PlantSense AI. For professional advice, consult a local agronomist.', { align: 'center' });
      doc.text('© 2026 PlantSense AI. All rights reserved.', { align: 'center' });

      doc.end();
    } catch (error) {
      reject(error);
    }
  });
};

export default { generatePDFReport };
